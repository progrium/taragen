package design

import (
	"fmt"
	"strings"
	"time"
)

// Graph renders the dependency graph as Mermaid. An edge points from a
// dependency to the proposal that needs it.
func (r *Repo) Graph(now time.Time) string {
	var b strings.Builder
	b.WriteString("graph TD\n")
	id := func(slug string) string { return "p_" + strings.ReplaceAll(slug, "-", "_") }
	for _, p := range r.Proposals {
		label := p.Status
		if s := r.State(p, now); s != "" {
			label += ", " + s
		}
		fmt.Fprintf(&b, "  %s[\"%s<br/><i>%s</i>\"]\n", id(p.Slug), p.Slug, label)
	}
	for _, p := range r.Proposals {
		for _, d := range p.Depends {
			if r.BySlug[d] != nil {
				fmt.Fprintf(&b, "  %s --> %s\n", id(d), id(p.Slug))
			}
		}
	}
	return b.String()
}

// Index renders the generated status index: a table of every proposal, in
// the order they were written, and the dependency graph.
func (r *Repo) Index(now time.Time) string {
	var b strings.Builder
	b.WriteString("<!-- Generated by `go run ./tools/design status` on main. Do not edit, and do not commit it in a PR. -->\n\n")
	b.WriteString("# Proposal status\n\n")
	b.WriteString("See [the design process](README.md) for what each status and state means.\n\n")
	b.WriteString("| Proposal | Issue | Status | State | Title |\n")
	b.WriteString("| --- | --- | --- | --- | --- |\n")
	for _, p := range r.Proposals {
		issue := ""
		if p.Issue != 0 {
			issue = fmt.Sprintf("#%d", p.Issue)
		}
		fmt.Fprintf(&b, "| [%s](%s.md) | %s | %s | %s | %s |\n",
			p.Slug, p.Slug, issue, p.Status, r.State(p, now), strings.ReplaceAll(p.Title, "|", `\|`))
	}
	b.WriteString("\n## Dependencies\n\n```mermaid\n")
	b.WriteString(r.Graph(now))
	b.WriteString("```\n")
	return b.String()
}
